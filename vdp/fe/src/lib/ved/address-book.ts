/** Нормализация строки для нечувствительного к регистру поиска. */
function norm(value: string): string {
  return value.trim().toLowerCase().replace(/\s+/g, " ");
}

/**
 * Возвращает подсказки адресов по введённому тексту.
 * Сначала совпадения с начала строки, затем вхождения внутри.
 */
export function suggestAddresses(
  query: string,
  extra: readonly string[] = [],
  limit = 8,
): string[] {
  const pool = Array.from(new Set([...extra.filter(Boolean), ...ADDRESS_BOOK]));
  const q = norm(query);
  if (!q) return pool.slice(0, limit);
  const starts: string[] = [];
  const contains: string[] = [];
  for (const item of pool) {
    const n = norm(item);
    if (n.startsWith(q)) starts.push(item);
    else if (n.includes(q)) contains.push(item);
  }
  return [...starts, ...contains].slice(0, limit);
}
