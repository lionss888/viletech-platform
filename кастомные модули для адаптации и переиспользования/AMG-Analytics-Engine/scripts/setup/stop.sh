#!/bin/bash

echo "🛑 Остановка системы АБС..."
echo "========================================"

# Остановка контейнеров
echo "📦 Остановка контейнеров Docker..."
docker-compose down

if [ $? -eq 0 ]; then
    echo "✅ Контейнеры остановлены"
else
    echo "❌ Ошибка при остановке контейнеров"
    exit 1
fi

# Проверка что все контейнеры остановлены
echo ""
echo "🔍 Проверка статуса..."
if docker ps | grep -q "abs_"; then
    echo "⚠️  Некоторые контейнеры все еще работают:"
    docker ps | grep "abs_"
else
    echo "✅ Все контейнеры остановлены"
fi

echo ""
echo "🎯 Система остановлена!"
echo "Для повторного запуска используйте: ./scripts/setup/start.sh"
