/**
 * Returns BDUI action ids allowed for a ВИ role at the given form status.
 * Covers happy-path import+аванс and postpay/corrections/cancel branches.
 */
export function resolveLifecycleActionIds(
  role: BduiVedRoleId,
  status: StatusKey | undefined,
): string[] {
  if (!status) {
    return [];
  }
  const matrix = ROLE_MATRICES[role];
  if (!matrix) {
    return [];
  }
  return [...(matrix[status] ?? [])];
}

/**
 * True when the role has no CTA for this status (including unknown statuses).
 */
export function hasNoLifecycleActions(role: BduiVedRoleId, status: StatusKey): boolean {
  return resolveLifecycleActionIds(role, status).length === 0;
}
